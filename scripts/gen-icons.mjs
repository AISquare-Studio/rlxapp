#!/usr/bin/env node
// Generates every app icon from rlx's logo, src/assets/rlx-logo.svg.
//
//   npm run icons
//
// 1. Writes src-tauri/icons/master.svg, a 1024 px master. It is the r\x mark centred on
//    a rlx-ground (#08090B) tile laid out on the macOS icon grid: an 824 px tile inset
//    100 px, with a corner radius of 185 px.
// 2. Writes public/favicon.svg, the same mark on a full-bleed tile.
// 3. Runs `tauri icon` on the master to produce the macOS .icns, the Windows .ico and the
//    Linux PNGs in src-tauri/icons/. Then it deletes the mobile and Windows Store
//    outputs, which this desktop app doesn't ship.
//
// The mark's path data is copied verbatim; only its placement changes.
// src/brand/brand.test.tsx checks that every generated SVG carries the logo's paths
// unchanged.
import { spawnSync } from "node:child_process";
import { copyFileSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const logoFile = join(root, "src/assets/rlx-logo.svg");
const iconsDir = join(root, "src-tauri/icons");
const masterFile = join(iconsDir, "master.svg");
const faviconFile = join(root, "public/favicon.svg");

const GROUND = "#08090B";
const MARK = "#2F74F0";

const logo = readFileSync(logoFile, "utf8");
const viewBox = logo.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
if (!viewBox) throw new Error(`no viewBox in ${logoFile}`);
const [markW, markH] = [Number(viewBox[1]), Number(viewBox[2])];
const paths = [...logo.matchAll(/<path\b[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
if (paths.length === 0) throw new Error(`no <path d=…> in ${logoFile}`);

/** An SVG of `size` px: a rounded `tile` square at `inset`, the mark `markWidth` px wide in its centre. */
function iconSvg({ size, inset, radius, markWidth, comment }) {
  const tile = size - 2 * inset;
  const scale = markWidth / markW;
  const x = (size - markW * scale) / 2;
  const y = (size - markH * scale) / 2;
  const fmt = (n) => Number(n.toFixed(4));
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">`,
    `<!-- ${comment} Generated by scripts/gen-icons.mjs from src/assets/rlx-logo.svg; do not edit. -->`,
    `<!-- The mark: JetBrains Mono glyphs, Copyright 2020 The JetBrains Mono Project Authors, SIL Open Font License 1.1. -->`,
    `<rect x="${inset}" y="${inset}" width="${tile}" height="${tile}" rx="${radius}" fill="${GROUND}"/>`,
    `<g transform="translate(${fmt(x)} ${fmt(y)}) scale(${fmt(scale)})">`,
    ...paths.map((d) => `<path fill="${MARK}" d="${d}"/>`),
    `</g>`,
    `</svg>`,
    "",
  ].join("\n");
}

writeFileSync(
  masterFile,
  iconSvg({ size: 1024, inset: 100, radius: 185, markWidth: 0.62 * 824, comment: "rlx app icon master (1024 px, macOS grid)." }),
);
writeFileSync(
  faviconFile,
  iconSvg({ size: 64, inset: 0, radius: 14, markWidth: 0.78 * 64, comment: "rlx favicon." }),
);
console.log(`wrote ${masterFile}\nwrote ${faviconFile}`);

const require = createRequire(import.meta.url);
const tauriCli = require.resolve("@tauri-apps/cli/tauri.js");
const result = spawnSync(process.execPath, [tauriCli, "icon", masterFile, "--output", iconsDir], {
  cwd: root,
  stdio: "inherit",
});
if (result.status !== 0) process.exit(result.status ?? 1);

const unshipped = /^(android|ios|Square\d+x\d+Logo\.png|StoreLogo\.png|64x64\.png)$/;
for (const entry of readdirSync(iconsDir)) {
  if (unshipped.test(entry)) rmSync(join(iconsDir, entry), { recursive: true, force: true });
}
console.log("pruned mobile and Windows Store icons");

// 4. The menu-bar / system-tray icon: the same paths, single colour, on a transparent square.
//    tray.svg is black, used as a macOS template image (it follows light and dark menu bars).
//    tray-light.svg is white and tray-dark.svg black, for dark and light trays on Windows/Linux.
//    Each is rasterised to a 64 px PNG beside it. src/brand/brand.test.tsx checks the paths.
function traySvg(fill, comment) {
  const size = 64;
  const width = 0.94 * size;
  const scale = width / markW;
  const x = (size - width) / 2;
  const y = (size - markH * scale) / 2;
  return [
    `<!-- ${comment} The r\\x mark's paths, copied verbatim from src/assets/rlx-logo.svg. -->`,
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">`,
    `  <g transform="translate(${x.toFixed(3)} ${y.toFixed(3)}) scale(${scale.toFixed(6)})" fill="${fill}">`,
    ...paths.map((d) => `    <path d="${d}"/>`),
    "  </g>",
    "</svg>",
    "",
  ].join("\n");
}

const trays = [
  ["tray", "#000000", "rlx tray icon, macOS template (black, alpha only)."],
  ["tray-light", "#FFFFFF", "rlx tray icon for dark trays (white)."],
  ["tray-dark", "#000000", "rlx tray icon for light trays (black)."],
];
for (const [name, fill, comment] of trays) {
  const svgFile = join(iconsDir, `${name}.svg`);
  writeFileSync(svgFile, traySvg(fill, comment));
  const out = mkdtempSync(join(tmpdir(), "rlx-tray-"));
  const raster = spawnSync(process.execPath, [tauriCli, "icon", svgFile, "--output", out, "--png", "64"], {
    cwd: root,
    stdio: "inherit",
  });
  if (raster.status !== 0) process.exit(raster.status ?? 1);
  copyFileSync(join(out, "64x64.png"), join(iconsDir, `${name}.png`));
  rmSync(out, { recursive: true, force: true });
  console.log(`wrote ${svgFile} and ${name}.png`);
}
